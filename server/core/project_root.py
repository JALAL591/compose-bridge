# -*- coding: utf-8 -*-
"""
Unified Project Root Resolver

Precedence:
1. Explicit argument (passed by caller)
2. Environment variable COMPOSEBRIDGE_ROOT
3. Config file .composebridge/config.json
4. Auto-detect from file location
"""

import os
import json
from pathlib import Path
from typing import Optional


def _auto_detect_root() -> Path:
    """Auto-detect project root based on file location."""
    current = Path(__file__).resolve()
    for parent in [current] + list(current.parents):
        # If we find bridge/ or app/ or server/ — it's likely the root
        if (parent / "bridge").exists() or (parent / "app").exists() or (parent / "server").exists():
            return parent
    # Fallback: current working directory
    return Path.cwd()


def _from_env() -> Optional[Path]:
    env = os.environ.get("COMPOSEBRIDGE_ROOT")
    if env:
        p = Path(env)
        if p.exists():
            return p
    return None


def _from_config() -> Optional[Path]:
    # Check .composebridge/config.json in current dir or auto-detected root
    candidates = [
        Path.cwd() / ".composebridge" / "config.json",
        _auto_detect_root() / ".composebridge" / "config.json",
    ]
    for cfg in candidates:
        if cfg.exists():
            try:
                data = json.loads(cfg.read_text(encoding="utf-8"))
                root = data.get("project_root")
                if root:
                    p = Path(root)
                    if p.exists():
                        return p
            except Exception:
                pass
    return None


def get_project_root(explicit: Optional[Path] = None, no_config: bool = False) -> Path:
    import sys
    for i, arg in enumerate(sys.argv):
        if arg == "--root" and i + 1 < len(sys.argv):
            p = Path(sys.argv[i + 1]).resolve()
            if p.exists():
                return p
        elif arg.startswith("--root="):
            p = Path(arg.split("=", 1)[1]).resolve()
            if p.exists():
                return p
    """
    Get the project root using the precedence rules.

    Args:
        explicit: explicit path (highest priority)
        no_config: if True, ignore .composebridge/config.json

    Returns:
        Path to project root
    """
    if explicit:
        p = Path(explicit).resolve()
        if p.exists():
            return p

    env = _from_env()
    if env:
        return env.resolve()

    if not no_config:
        cfg = _from_config()
        if cfg:
            return cfg.resolve()

    return _auto_detect_root()

def clean_temp_files(project_root: Optional[Path] = None) -> dict:
    """
    Safely cleans temporary cache, state files, and logs to avoid Search Everywhere clutter in IDE.

    Safe to delete:
    - .composebridge-state/ folder contents
    - .composebridge-journal.json
    - Temporary *.tmp and *.log files generated by composebridge

    NEVER deletes:
    - Any .kt or .kts source files
    - Any .bridge.bak backup files
    - Any files inside build/, dist/, .gradle/, .git/
    """
    try:
        from core.clean_cache_guard import should_allow_clean_cache
    except ImportError:
        from server.core.clean_cache_guard import should_allow_clean_cache
    can_clean, msg = should_allow_clean_cache(project_root)
    if not can_clean:
        return {"success": False, "error": msg, "error_code": "PENDING_EDITS_EXIST"}

    import shutil
    root = Path(project_root) if project_root else get_project_root()
    deleted_items = []

    # 1. Clear .composebridge-state/ contents except auth_token.txt and auth.json (Token Persistence)
    state_dir = root / ".composebridge-state"
    if state_dir.exists() and state_dir.is_dir():
        try:
            for child in state_dir.iterdir():
                if child.name not in ("auth_token.txt", "auth.json"):
                    if child.is_file() or child.is_symlink():
                        child.unlink()
                        deleted_items.append(f".composebridge-state/{child.name}")
                    elif child.is_dir():
                        shutil.rmtree(child, ignore_errors=True)
                        deleted_items.append(f".composebridge-state/{child.name}/")
        except Exception:
            pass

    # 2. Delete legacy .composebridge-journal.json
    legacy_journal = root / ".composebridge-journal.json"
    if legacy_journal.exists() and legacy_journal.is_file():
        try:
            legacy_journal.unlink()
            deleted_items.append(".composebridge-journal.json")
        except Exception:
            pass

    # 3. Delete root-level .tmp and temporary logs
    try:
        for item in root.glob("*.tmp"):
            if item.is_file():
                try:
                    item.unlink()
                    deleted_items.append(item.name)
                except Exception:
                    pass

        for item in root.glob(".tmp_*"):
            if item.is_file() and not item.name.endswith(".kt") and not item.name.endswith(".bridge.bak"):
                try:
                    item.unlink()
                    deleted_items.append(item.name)
                except Exception:
                    pass

        for log_name in ["composebridge.log", "bridge_server.log", "composebridge_scanner.log"]:
            log_file = root / log_name
            if log_file.exists() and log_file.is_file():
                try:
                    log_file.unlink()
                    deleted_items.append(log_name)
                except Exception:
                    pass
    except Exception:
        pass

    return {
        "success": True,
        "deleted_count": len(deleted_items),
        "deleted_items": deleted_items,
        "message": "Temporary cache and logs cleaned safely."
    }

